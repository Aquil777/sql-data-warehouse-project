-- dimension exploration
-- identifying the unique values in each dimension

--- ex.: explore all countries our customers come from
select distinct country from gold.dim_customers;

-- ex.: explore all categories "the major divisions"
select distinct category, subcategory, product_name from gold.dim_products;

-- date exploration
-- identify the earliest and latest dates
-- understand the scope of data and timespan

--ex.: find the first and last order date
-- how many years of sales
select min(order_date) as first_order_date, max(order_date) as last_order_date,
datediff(year, min(order_date), max(order_date)) as years_sales from gold.fact_sales;

-- wx.: select the oldest and youngest customer
select min(birthdate) as oldest_customer, DATEDIFF(year, min(birthdate), getdate()) as oldest_age,
max(birthdate) as youngest_customer, DATEDIFF(year, max(birthdate), getdate()) as youngest_age
from gold.dim_customers;

